// FULL CASE FOLDING — the one place the JS port genuinely diverges from Python.
//
// Python's str.casefold applies Unicode FULL case folding (CaseFolding.txt C+F):
// "Straße".casefold() == "strasse". JavaScript has no full case folding —
// String.prototype.toLowerCase is the Default Case Conversion lowercase mapping,
// which leaves ß alone and leaves Greek final sigma ς alone. A port built on
// toLowerCase alone fails the German ß and Greek final-sigma conformance
// vectors (ADR-0011). Go has the same gap and closes it with
// golang.org/x/text/cases.Fold; JS has no equivalent in the platform or in a
// dependency we are willing to take, so the delta is carried explicitly.
//
// This table is exactly the set of code points where Python's casefold disagrees
// with a PER-CODE-POINT JavaScript toLowerCase, so
//
//     foldCodePoint(cp) = CASEFOLD_OVERRIDES.get(cp) ?? lowerOneCodePoint(cp)
//
// reproduces str.casefold code point for code point. Folding one code point at a
// time is deliberate: it also sidesteps toLowerCase's context-sensitive
// final-sigma rule ("ΟΣ".toLowerCase() === "ος"), which casefold does not have.
//
// DERIVED, not hand-written. Regenerate against the reference with:
//
//   node -e 'const o=[];for(let c=0;c<=0x10FFFF;c++){if(c>=0xD800&&c<=0xDFFF)continue;
//     const ch=String.fromCodePoint(c),lo=ch.toLowerCase();if(lo!==ch)o.push([c,lo]);}
//     require("fs").writeFileSync("jslower.json",JSON.stringify(o))'
//   python3 -c 'import json;jl={int(k):v for k,v in dict(json.load(open("jslower.json"))).items()};
//     print(json.dumps({c:chr(c).casefold() for c in range(0x110000)
//       if not 0xD800<=c<=0xDFFF and chr(c).casefold()!=jl.get(c,chr(c))},ensure_ascii=False))'
//
// 325 entries, Python unicodedata 16.0.0 / Node ICU 17.0. A Unicode version skew
// between the two runtimes is the residual risk; the conformance vectors are what
// catch it.

